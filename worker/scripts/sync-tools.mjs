// Copies TOOL_SCHEMAS from assistant/tools.js into worker/src/tool-schemas.js.
//   node scripts/sync-tools.mjs          write the copy
//   node scripts/sync-tools.mjs --check  exit 1 if the copy is out of date (run before every deploy)
// The worker bundles this static copy instead of assistant/tools.js, which also contains
// browser/Node code the Worker does not need.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const { TOOL_SCHEMAS } = require(path.join(here, "..", "..", "assistant", "tools.js"));
const target = path.join(here, "..", "src", "tool-schemas.js");

const text =
  "// GENERATED by worker/scripts/sync-tools.mjs from assistant/tools.js - do not edit by hand.\n" +
  "// Run `npm run sync-tools` after changing TOOL_SCHEMAS; `npm run deploy` refuses to deploy a stale copy.\n" +
  `export const TOOL_SCHEMAS = ${JSON.stringify(TOOL_SCHEMAS, null, 2)};\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== text) {
    console.error("worker/src/tool-schemas.js is out of date with assistant/tools.js. Run: npm run sync-tools");
    process.exit(1);
  }
  console.log(`tool-schemas.js matches assistant/tools.js (${TOOL_SCHEMAS.length} tools).`);
} else {
  writeFileSync(target, text);
  console.log(`Wrote src/tool-schemas.js (${TOOL_SCHEMAS.length} tools).`);
}
